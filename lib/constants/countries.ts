export const COUNTRY_BY_CODE: Record<string, WorldCountry> = Object.fromEntries(
  ALL_WORLD_COUNTRIES.map((c) => [c.code.toUpperCase(), c])
);

export function getCountry(code: string): WorldCountry | undefined {
  if (!code) return undefined;
  return COUNTRY_BY_CODE[code.toUpperCase()];
}

export function getCountryFlagUrl(code: string, size: 20 | 40 | 80 | 160 = 40): string {
  if (!code) return "";
  return `https://flagcdn.com/w${size}/${code.toLowerCase()}.png`;
}
